def amazon(q):
    from urllib.parse import quote_plus
    return ("buy", "amazon.de", "https://www.amazon.de/s?k=" + quote_plus(q) + "&i=stripbooks")

def ia(ident, label="Borrow free (archive.org)"):
    return ("borrow", label, "https://archive.org/details/" + ident)

def doi(d, label="Publisher (paywalled)"):
    return ("paywall", label, "https://doi.org/" + d)

def free(url, label="Free PDF"):
    return ("free", label, url)

def web(url, label="Website"):
    return ("web", label, url)

